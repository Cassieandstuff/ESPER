bool LookupCtdaFunc(uint16_t index, CtdaFuncInfo& out) {
    // kTable is sorted by index; binary search.
    const Row* begin = kTable;
    const Row* end   = kTable + (sizeof(kTable) / sizeof(kTable[0]));
    const Row* it = std::lower_bound(begin, end, index,
        [](const Row& r, uint16_t v) { return r.index < v; });
    if (it == end || it->index != index) return false;
    out.name = it->name;
    out.p1   = it->p1;
    out.p2   = it->p2;
    return true;
}

